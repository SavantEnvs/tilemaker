#!/usr/bin/env bash
#
# mayhem/build.sh — build tilemaker's fuzz targets and its unit tests.
#
# Three independent object trees under mayhem/out/ (gitignored):
#   fuzz/  clang++ + $SANITIZER_FLAGS + SanCov: the PbfReader libFuzzer harness and its
#          -standalone reproducer (pbf_reader.cpp + helpers.cpp + vendored libdeflate)
#   afl/   afl-clang-fast++ + $SANITIZER_FLAGS: the whole tilemaker program (the same
#          object list as upstream's Makefile `tilemaker` target), main renamed to
#          tilemaker_main and driven by mayhem/harnesses/tilemaker_fuzz_main.cpp
#   test/  normal flags (-O2, no sanitizers): upstream's minunit tests (Makefile `test`)
# The object lists mirror upstream's Makefile; it is not invoked directly because it
# needs a Lua interpreter on PATH and writes objects next to the sources.
set -euo pipefail
[ -n "${SOURCE_DATE_EPOCH:-}" ] || unset SOURCE_DATE_EPOCH

: "${SANITIZER_FLAGS=-fsanitize=address,undefined -fno-sanitize-recover=all -fno-omit-frame-pointer}"
: "${DEBUG_FLAGS:=-g -gdwarf-3}"
: "${CC:=clang}" ; : "${CXX:=clang++}" ; : "${LIB_FUZZING_ENGINE:=-fsanitize=fuzzer}"
: "${MAYHEM_JOBS:=$(nproc)}"
: "${COVERAGE_FLAGS=}"
: "${SRC:=/mayhem}"
export SANITIZER_FLAGS DEBUG_FLAGS CC CXX LIB_FUZZING_ENGINE MAYHEM_JOBS COVERAGE_FLAGS

cd "$SRC"
OUT="$SRC/mayhem/out"
BIN="$OUT/bin"
GEN="$OUT/gen"
mkdir -p "$BIN" "$GEN"

# src/config_schema.h is generated by upstream's Makefile from resources/config-schema.json.
{
  printf '#ifndef _CONFIG_SCHEMA_H\n#define _CONFIG_SCHEMA_H\n\nstatic const char* CONFIG_SCHEMA = R"TMCONFIGSCHEMA(\n'
  cat resources/config-schema.json
  printf '\n)TMCONFIGSCHEMA";\n\n#endif //_CONFIG_SCHEMA_H\n'
} > "$GEN/config_schema.h.tmp"
cmp -s "$GEN/config_schema.h.tmp" "$GEN/config_schema.h" 2>/dev/null || mv "$GEN/config_schema.h.tmp" "$GEN/config_schema.h"
rm -f "$GEN/config_schema.h.tmp"

LUA_INC=/usr/include/lua5.1
INC=(-I"$GEN" -isystem ./include -I./src -I"$LUA_INC")
LIBS=(-llua5.1 -lboost_program_options -lsqlite3 -lboost_filesystem -lboost_system -lshp -lz -pthread)
TM_VERSION="v$(sed -n '1p' VERSION)+mayhem"

DEFLATE=(adler32 arm/cpu_features crc32 deflate_compress deflate_decompress gzip_compress
         gzip_decompress utils x86/cpu_features zlib_compress zlib_decompress)
DEFLATE_SRCS=(); for d in "${DEFLATE[@]}"; do DEFLATE_SRCS+=("src/external/libdeflate/lib/$d.c"); done
SVB_SRCS=(src/external/streamvbyte_decode.c src/external/streamvbyte_encode.c src/external/streamvbyte_zigzag.c)
TM_CPP=(attribute_store config_validator coordinates_geom coordinates declutter geojson_processor
        geom helpers mbtiles mmap_allocator node_stores options_parser osm_lua_processing osm_mem_tiles
        osm_store output_object pbf_processor pbf_reader pmtiles pooled_string relation_roles
        sharded_node_store sharded_way_store shared_data shp_mem_tiles shp_processor significant_tags
        simplify_buildings sorted_node_store sorted_way_store tag_map tile_coordinates_set tile_data
        tile_sorting tilemaker tile_worker visvalingam way_stores)
TM_SRCS=(); for f in "${TM_CPP[@]}"; do TM_SRCS+=("src/$f.cpp"); done

# compile <objdir> <cc> <cxx> "<cflags>" "<cxxflags>" <src...>: one object per source, in
# parallel; sets OBJS to the object paths (in order). Fails if any compile fails.
compile() {
  local objdir="$1" cc="$2" cxx="$3" cflags="$4" cxxflags="$5"; shift 5
  local jobs=() objs=() s o
  for s in "$@"; do
    o="$objdir/${s%.*}.o"; objs+=("$o"); mkdir -p "$(dirname "$o")"
    case "$s" in
      *.c)   jobs+=("$cc $cflags -c $s -o $o ${INC[*]}") ;;
      *)     jobs+=("$cxx $cxxflags ${EXTRA_FLAGS[$s]:-} -c $s -o $o ${INC[*]}") ;;
    esac
  done
  printf '%s\n' "${jobs[@]}" | xargs -P "$MAYHEM_JOBS" -I{} sh -c '{}'
  OBJS=("${objs[@]}")
}

declare -A EXTRA_FLAGS=()
CXXSTD="-std=c++14 -pthread -Wno-unknown-pragmas -Wno-sign-compare -DTM_VERSION=$TM_VERSION"
CSTD="-std=c99 -Wno-unknown-pragmas"

# ---- 1) libFuzzer: PbfReader --------------------------------------------------------------
FZ_FLAGS="-O1 $SANITIZER_FLAGS $DEBUG_FLAGS"
compile "$OUT/fuzz" "$CC" "$CXX" \
  "$FZ_FLAGS -fsanitize=fuzzer-no-link $CSTD" "$FZ_FLAGS -fsanitize=fuzzer-no-link $CXXSTD" \
  src/pbf_reader.cpp src/helpers.cpp "${DEFLATE_SRCS[@]}"
FZ_OBJS=("${OBJS[@]}")
$CXX $FZ_FLAGS $CXXSTD -c mayhem/lsan_off.cc -o "$OUT/fuzz/lsan_off.o"
$CXX $FZ_FLAGS -fsanitize=fuzzer-no-link $CXXSTD "${INC[@]}" -c mayhem/harnesses/pbf_reader_fuzz.cpp -o "$OUT/fuzz/pbf_reader_fuzz.o"
$CC $FZ_FLAGS -c "$STANDALONE_FUZZ_MAIN" -o "$OUT/fuzz/standalone_main.o"
$CXX $FZ_FLAGS $LIB_FUZZING_ENGINE "$OUT/fuzz/pbf_reader_fuzz.o" "${FZ_OBJS[@]}" "$OUT/fuzz/lsan_off.o" \
  -lboost_system -pthread -o "$BIN/pbf_reader_fuzz"
$CXX $FZ_FLAGS "$OUT/fuzz/standalone_main.o" "$OUT/fuzz/pbf_reader_fuzz.o" "${FZ_OBJS[@]}" "$OUT/fuzz/lsan_off.o" \
  -lboost_system -pthread -o "$BIN/pbf_reader_fuzz-standalone"

# ---- 2) AFL: the tilemaker program ---------------------------------------------------------
# AFL instrumentation needs afl-clang-fast; it is not reached through the ccache masquerade
# (its code generation depends on AFL_* variables ccache does not hash).
AFL_CC=afl-clang-fast AFL_CXX=afl-clang-fast++
# rapidjson's internal::Stack does `stackTop_ + n` on a null stack (stack.h:117) for every
# document it parses, so UBSan's pointer-overflow check aborts every input before tilemaker
# runs. PooledString::data() (src/pooled_string.cpp:110) loads a pointer from a 1-byte-aligned
# uint8_t buffer at offset 8 for every tag string, so the alignment check also fires on every
# input. Only these two checks are relaxed, and only here; ASan and the rest of UBSan stay halting.
NO_PTR_OVF=""; case "$SANITIZER_FLAGS" in *undefined*) NO_PTR_OVF="-fno-sanitize=pointer-overflow,alignment" ;; esac
# ASan is off in this tree: with ASan every run of the whole program aborts at once with an
# "unknown-crash" READ on memory whose shadow is 00 (e.g. tilemaker.cpp:444, before any input
# is parsed), a runtime false positive rather than a finding. UBSan stays on and halting; the
# libFuzzer target above keeps ASan+UBSan.
AFL_SAN="${SANITIZER_FLAGS//-fsanitize=address,undefined/-fsanitize=undefined}"
AFL_SAN="${AFL_SAN//-fsanitize=address/}"
AFL_FLAGS="-O1 $AFL_SAN $NO_PTR_OVF $DEBUG_FLAGS"
# main() may end without `return` (C++ main rule); renamed to tilemaker_main it is an ordinary
# function, so UBSan's missing-return check is off for src/tilemaker.cpp in this tree only.
[ -n "$NO_PTR_OVF" ] && EXTRA_FLAGS[src/tilemaker.cpp]="-fno-sanitize=return"
AFL_QUIET=1 compile "$OUT/afl" "$AFL_CC" "$AFL_CXX" \
  "$AFL_FLAGS $CSTD" "$AFL_FLAGS $CXXSTD -Dmain=tilemaker_main" \
  "${TM_SRCS[@]}" "${SVB_SRCS[@]}" "${DEFLATE_SRCS[@]}"
AFL_OBJS=("${OBJS[@]}")
AFL_QUIET=1 $AFL_CXX $AFL_FLAGS $CXXSTD -c mayhem/lsan_off.cc -o "$OUT/afl/lsan_off.o"
AFL_QUIET=1 $AFL_CXX $AFL_FLAGS $CXXSTD "${INC[@]}" -c mayhem/harnesses/tilemaker_fuzz_main.cpp -o "$OUT/afl/tilemaker_fuzz_main.o"
AFL_QUIET=1 $AFL_CXX $AFL_FLAGS "$OUT/afl/tilemaker_fuzz_main.o" "${AFL_OBJS[@]}" "$OUT/afl/lsan_off.o" \
  "${LIBS[@]}" -o "$BIN/tilemaker_fuzz"

EXTRA_FLAGS=()
# ---- 3) upstream unit tests, normal flags --------------------------------------------------
T_FLAGS="-O2 $COVERAGE_FLAGS"
TOBJ="$OUT/test"
LIB_SRCS=(); for s in "${TM_SRCS[@]}"; do [ "$s" = src/tilemaker.cpp ] || LIB_SRCS+=("$s"); done
compile "$TOBJ" "$CC" "$CXX" "$T_FLAGS $CSTD" "$T_FLAGS $CXXSTD" \
  "${LIB_SRCS[@]}" "${SVB_SRCS[@]}" "${DEFLATE_SRCS[@]}" test/*.test.cpp
o() { for x in "$@"; do printf '%s\n' "$TOBJ/$x.o"; done; }
DFL=(); for d in "${DEFLATE[@]}"; do DFL+=("src/external/libdeflate/lib/$d"); done
SVB=(src/external/streamvbyte_decode src/external/streamvbyte_encode src/external/streamvbyte_zigzag)
# test.shp_mem_tiles is left out: the binary hangs (no output, never exits) in this image.
declare -A TESTS=(
  [append_vector]="src/mmap_allocator"
  [attribute_store]="src/mmap_allocator src/attribute_store src/pooled_string"
  [config_validator]="src/config_validator"
  [correct]=""
  [deque_map]=""
  [geom]="src/geom"
  [helpers]="src/helpers ${DFL[*]}"
  [options_parser]="src/options_parser"
  [osm_store]=""
  [pbf_reader]="src/helpers src/pbf_reader ${DFL[*]}"
  [pooled_string]="src/mmap_allocator src/pooled_string"
  [relation_roles]="src/relation_roles"
  [significant_tags]="src/significant_tags src/tag_map"
  [sorted_node_store]="${SVB[*]} src/mmap_allocator src/sorted_node_store"
  [sorted_way_store]="${SVB[*]} src/mmap_allocator src/sorted_way_store"
  [tile_coordinates_set]="src/tile_coordinates_set"
)
mkdir -p "$BIN/tests"
for t in "${!TESTS[@]}"; do
  # shellcheck disable=SC2086
  mapfile -t objs < <(o ${TESTS[$t]} "test/$t.test")
  $CXX $T_FLAGS $CXXSTD "${objs[@]}" "${LIBS[@]}" -o "$BIN/tests/test.$t"
done
echo "built: $(ls "$BIN" "$BIN/tests" | tr '\n' ' ')"
